def normalize(code):
    """Map a locale like 'es_MX', 'zh-Hant-TW' or 'pt_BR' to a supported language."""
    code = (code or "").replace("-", "_")
    low = code.lower()
    if low.startswith("zh"):
        if any(x in low for x in ("tw", "hk", "mo", "hant")):
            return "zh_TW"
        return "zh_CN"
    base = low.split("_")[0]
    return base if base in STRINGS else "en"


def detect_language():
    """Anki's interface language, then the system language."""
    code = ""
    try:
        import anki.lang

        code = getattr(anki.lang, "current_lang", "") or ""
    except Exception:
        pass
    if not code:
        try:
            from aqt.qt import QLocale

            code = QLocale.system().name()
        except Exception:
            code = ""
    return normalize(code)


_lang = "en"


def set_language(setting):
    """setting is "auto" or a language code from LANGUAGE_NAMES."""
    global _lang
    _lang = setting if setting in STRINGS else detect_language()


def current_language():
    return _lang


def tr(_key, /, **kwargs):
    text = STRINGS.get(_lang, {}).get(_key) or STRINGS["en"].get(_key, _key)
    return text.format(**kwargs) if kwargs else text
